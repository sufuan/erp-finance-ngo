<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;

/**
 * Regenerates docs/schema.md from the live database (plan protocol item 8:
 * the schema dump is refreshed at the end of every step so the next agent
 * session pastes facts, not guesses).
 */
class SchemaMarkdown extends Command
{
    protected $signature = 'schema:markdown {--path=docs/schema.md}';

    protected $description = 'Write a Markdown summary of the database schema to docs/schema.md';

    public function handle(): int
    {
        $db = DB::connection()->getDatabaseName();
        $tables = DB::select(
            'SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME',
            [$db]
        );

        $out = ["# Database schema — `{$db}`", '', 'Generated by `php artisan schema:markdown`. Refreshed at the end of every build step.', ''];

        foreach ($tables as $t) {
            $name = $t->TABLE_NAME;
            $out[] = "## {$name}";
            $out[] = '';
            $out[] = '| Column | Type | Null | Key | Default |';
            $out[] = '|---|---|---|---|---|';
            $cols = DB::select(
                'SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_KEY, COLUMN_DEFAULT
                 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION',
                [$db, $name]
            );
            foreach ($cols as $c) {
                $default = $c->COLUMN_DEFAULT === null ? '' : str_replace('|', '\\|', (string) $c->COLUMN_DEFAULT);
                $out[] = "| {$c->COLUMN_NAME} | {$c->COLUMN_TYPE} | {$c->IS_NULLABLE} | {$c->COLUMN_KEY} | {$default} |";
            }
            $out[] = '';
        }

        $path = base_path($this->option('path'));
        file_put_contents($path, implode("\n", $out));
        $this->info("Wrote {$path} (".count($tables).' tables)');

        return self::SUCCESS;
    }
}
